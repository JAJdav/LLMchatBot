@app.get("/", response_class=HTMLResponse)
def home():
    return "<h1>Gemini FastAPI Endpoint</h1>"

@app.post("/chat")
def post_data(request: ChatRequest):
    try:

        case_obj = get_case_by_id(request.case_id)
        case_json_str = json.dumps(case_obj.model_dump(mode="json"), indent=2)

        user_query = request.message.strip()


        user_content = (
            f"[CASE DATA PAYLOAD]\n"
            f"```json\n{case_json_str}\n```\n\n"
            f"[INVESTIGATOR QUERY]\n{user_query}"
        )

        # 3. Send structured array to OpenRouter
        completion = client.chat.completions.create(
            extra_headers={
                "HTTP-Referer": "http://localhost:8000",
                "X-Title": "FastAPI App",
            },
            model="google/gemma-4-31b-it",
            messages=[
                {"role": "system", "content": SYSTEM_INSTRUCTION},
                {"role": "user", "content": user_content},
            ],
            max_tokens=1000,
            temperature=0.1,  
        )

        return {
            "message": "success",
            "case_id": request.case_id,
            "response": completion.choices[0].message.content
        }

    except Exception as e:

        raise HTTPException(status_code=500, detail=str(e))